#!/usr/bin/env bash
# Install ATW as a per-user systemd service.  Never installs as root.
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ATW_HOME="${ATW_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/atw}"
PYTHON="${ATW_PYTHON:-python3}"
NO_INSTALL=0
ENABLE_LINGER=0

usage() {
  cat <<'EOF'
Usage: deploy/linux/install.sh [options]
  --home PATH        ATW_HOME (default: ${XDG_DATA_HOME:-$HOME/.local/share}/atw)
  --python PATH      Python >=3.11 interpreter (default: python3)
  --no-install       do not create/refresh the venv or pip install the project
  --enable-linger    attempt `sudo loginctl enable-linger $USER` for boot without login
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --home) ATW_HOME="$2"; shift 2 ;;
    --python) PYTHON="$2"; shift 2 ;;
    --no-install) NO_INSTALL=1; shift ;;
    --enable-linger) ENABLE_LINGER=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage; exit 2 ;;
  esac
done

if [[ "$(id -u)" -eq 0 ]]; then
  echo "Refusing to install ATW as root. Run as the compute user." >&2
  exit 1
fi
if [[ ! -x "$PYTHON" ]] && ! command -v "$PYTHON" >/dev/null 2>&1; then
  echo "Python interpreter not found: $PYTHON" >&2
  exit 1
fi
PY_VER="$("$PYTHON" -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
"$PYTHON" - <<'PY'
import sys
if sys.version_info < (3, 11):
    raise SystemExit("ATW requires Python >= 3.11")
PY

if [[ "$NO_INSTALL" -eq 0 ]]; then
  if [[ ! -x "$ATW_HOME/venv/bin/python" ]]; then
    mkdir -p "$ATW_HOME"
    "$PYTHON" -m venv "$ATW_HOME/venv"
  fi
  PYTHON="$ATW_HOME/venv/bin/python"
  "$PYTHON" -m pip install --upgrade pip >/dev/null
  "$PYTHON" -m pip install -e "$PROJECT_ROOT"
fi
"$PYTHON" -c 'import atw; print("ATW", atw.__version__)'

mkdir -p "$ATW_HOME/config" "$ATW_HOME/tasks/inbox" "$ATW_HOME/tasks/accepted" \
  "$ATW_HOME/tasks/rejected" "$ATW_HOME/tasks/archive" "$ATW_HOME/receipts" \
  "$ATW_HOME/data" "$ATW_HOME/logs" "$HOME/.config/atw"
chmod 700 "$ATW_HOME" "$HOME/.config/atw" 2>/dev/null || true
if [[ ! -f "$ATW_HOME/config/config.yaml" ]]; then
  umask 077
  cat > "$ATW_HOME/config/config.yaml" <<EOF
# Generated by ATW install.sh. Adjust allowed_read_roots to your project dirs.
instance_id: $(hostname)
scan_interval_seconds: 5
sample_interval_seconds: 10
outbox_interval_seconds: 2
finalize_grace_seconds: 15
timezone: ""
allowed_read_roots:
  - $HOME
  - /tmp
notification:
  provider: auto
  webhook_env: ATW_DINGTALK_WEBHOOK
  secret_env: ATW_DINGTALK_SECRET
  rate_limit_per_minute: 15
health_summary:
  enabled: false
  time: "08:00"
EOF
  chmod 600 "$ATW_HOME/config/config.yaml"
  echo "created $ATW_HOME/config/config.yaml"
fi
if [[ ! -f "$HOME/.config/atw/atw.env" ]]; then
  umask 077
  cat > "$HOME/.config/atw/atw.env" <<'EOF'
# ATW secrets (mode 0600, never commit). Uncomment and fill in.
# ATW_DINGTALK_WEBHOOK=https://oapi.dingtalk.com/robot/send?access_token=...
# ATW_DINGTALK_SECRET=SEC...
EOF
  chmod 600 "$HOME/.config/atw/atw.env"
  echo "created $HOME/.config/atw/atw.env (edit to add DingTalk credentials)"
fi

UNIT_DIR="$HOME/.config/systemd/user"
mkdir -p "$UNIT_DIR"
cat > "$UNIT_DIR/atw.service" <<EOF
[Unit]
Description=Agent Task Watcher (ATW) local task supervisor
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$PROJECT_ROOT
Environment=ATW_HOME=$ATW_HOME
Environment=PYTHONUNBUFFERED=1
EnvironmentFile=-%h/.config/atw/atw.env
ExecStart=$PYTHON -m atw --home $ATW_HOME service run
Restart=always
RestartSec=10
KillSignal=SIGTERM
TimeoutStopSec=30
NoNewPrivileges=true

[Install]
WantedBy=default.target
EOF

systemctl --user daemon-reload
systemctl --user enable atw.service
systemctl --user restart atw.service
sleep 1
if ! systemctl --user is-active --quiet atw.service; then
  echo "ATW service failed to become active." >&2
  systemctl --user --no-pager status atw.service || true
  journalctl --user -u atw.service -n 30 --no-pager || true
  exit 1
fi
systemctl --user --no-pager status atw.service || true

LINGER="$(loginctl show-user "$USER" -p Linger --value 2>/dev/null || echo unknown)"
if [[ "$LINGER" != "yes" ]]; then
  echo
  echo "NOTE: linger is '$LINGER'. For boot without an interactive login run:"
  echo "      sudo loginctl enable-linger $USER"
  if [[ "$ENABLE_LINGER" -eq 1 ]]; then
    sudo loginctl enable-linger "$USER"
    echo "linger enabled."
  fi
fi
echo "ATW installed. Check: $PYTHON -m atw --home $ATW_HOME doctor"
