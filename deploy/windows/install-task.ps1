<#
.SYNOPSIS
  Install ATW as a per-user Windows Task Scheduler task.
.DESCRIPTION
  Uses the Task Scheduler COM API (the CIM Register-ScheduledTask cmdlet can be
  denied even when COM registration for the current user is allowed).

  AtStartup (default) uses a BootTrigger with an S4U principal so the task runs
  without an interactive login.  Creating that definition requires an elevated
  shell / policy permission; if denied, this script fails with an explanation.
  AtLogOn is a non-elevated fallback (runs under the interactive user token and
  is NOT equivalent to boot/no-login).

  The task runs `python -m atw --home <ATW_HOME> service run`.
  DingTalk credentials come from the user's ATW_DINGTALK_WEBHOOK and
  ATW_DINGTALK_SECRET environment variables.  No secret is written to the
  repository or printed.
.PARAMETER Python
  Absolute path to python.exe (>= 3.11).
.PARAMETER AtwHome
  ATW_HOME. Default: %LOCALAPPDATA%\ATW.
.PARAMETER TaskName
  Scheduled task name. Default: ATW.
.PARAMETER User
  Account for the task. Default: current user.
.PARAMETER TriggerType
  AtStartup (requires elevation) or AtLogOn (non-elevated fallback).
.PARAMETER NoStart
  Register but do not start immediately.
.PARAMETER Force
  Replace an existing task with the same name.
#>
[CmdletBinding()]
param(
    [string]$Python = "",
    [string]$AtwHome = "",
    [string]$TaskName = "ATW",
    [string]$User = "$env:USERDOMAIN\$env:USERNAME",
    [ValidateSet("AtStartup", "AtLogOn")]
    [string]$TriggerType = "AtStartup",
    [switch]$NoStart,
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path

if (-not $Python) {
    $cmd = Get-Command python -ErrorAction SilentlyContinue
    if (-not $cmd) { throw "python.exe not found; pass -Python <absolute path>" }
    $Python = $cmd.Source
}
$Python = (Resolve-Path $Python).Path
if (-not $AtwHome) { $AtwHome = Join-Path $env:LOCALAPPDATA "ATW" }
$AtwHome = [System.IO.Path]::GetFullPath($AtwHome)

& $Python -c "import sys; raise SystemExit(0 if sys.version_info >= (3, 11) else 1)"
if ($LASTEXITCODE -ne 0) { throw "ATW requires Python >= 3.11: $Python" }
& $Python -c "import atw"
if ($LASTEXITCODE -ne 0) {
    throw "ATW is not importable with $Python. Run: $Python -m pip install -e `"$ProjectRoot`""
}

foreach ($dir in @(
    $AtwHome,
    (Join-Path $AtwHome "config"),
    (Join-Path $AtwHome "tasks\inbox"),
    (Join-Path $AtwHome "tasks\accepted"),
    (Join-Path $AtwHome "tasks\rejected"),
    (Join-Path $AtwHome "tasks\archive"),
    (Join-Path $AtwHome "receipts"),
    (Join-Path $AtwHome "data"),
    (Join-Path $AtwHome "logs")
)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }

$configFile = Join-Path $AtwHome "config\config.yaml"
if (-not (Test-Path $configFile)) {
    $yaml = @"
# Generated by ATW install-task.ps1. Add project directories you need to watch.
instance_id: $env:COMPUTERNAME
scan_interval_seconds: 5
sample_interval_seconds: 10
outbox_interval_seconds: 2
finalize_grace_seconds: 15
allowed_read_roots:
  - $($env:USERPROFILE -replace '\\', '/')
  - $($env:TEMP -replace '\\', '/')
  - $($ProjectRoot -replace '\\', '/')
notification:
  provider: auto
  webhook_env: ATW_DINGTALK_WEBHOOK
  secret_env: ATW_DINGTALK_SECRET
  rate_limit_per_minute: 15
health_summary:
  enabled: false
  time: "08:00"
"@
    Set-Content -Path $configFile -Value $yaml -Encoding UTF8
    Write-Host "created $configFile"
}
$userWebhook = [Environment]::GetEnvironmentVariable("ATW_DINGTALK_WEBHOOK", "User")
$userSecret = [Environment]::GetEnvironmentVariable("ATW_DINGTALK_SECRET", "User")
if ((-not $env:ATW_DINGTALK_WEBHOOK -and -not $userWebhook) -or (-not $env:ATW_DINGTALK_SECRET -and -not $userSecret)) {
    Write-Warning "DingTalk credentials are not set (shell or User env). ATW will use mock notifications until ATW_DINGTALK_WEBHOOK / ATW_DINGTALK_SECRET exist for this user."
}

$service = New-Object -ComObject Schedule.Service
$service.Connect()
$folder = $service.GetFolder("\")
if (-not $Force) {
    try {
        $folder.GetTask($TaskName) | Out-Null
        throw "Scheduled task '$TaskName' already exists; use -Force to replace it"
    } catch [System.Runtime.InteropServices.COMException] {
        # Task not found (0x80070002) is expected.
    }
}

$task = $service.NewTask(0)
$task.RegistrationInfo.Description = "Agent Task Watcher V1 local supervisor"
$task.Settings.Enabled = $true
$task.Settings.ExecutionTimeLimit = "PT0S"
$task.Settings.MultipleInstances = 2          # IgnoreNew
$task.Settings.StartWhenAvailable = $true
$task.Settings.DisallowStartIfOnBatteries = $false
$task.Settings.StopIfGoingOnBatteries = $false
$task.Settings.RestartCount = 999
$task.Settings.RestartInterval = "PT1M"

$task.Principal.UserId = $User
$task.Principal.RunLevel = 0                  # least privilege
if ($TriggerType -eq "AtStartup") {
    $trig = $task.Triggers.Create(8)          # TASK_TRIGGER_BOOT
    $task.Principal.LogonType = 2             # TASK_LOGON_S4U
    $registerLogonType = 2
} else {
    $trig = $task.Triggers.Create(9)          # TASK_TRIGGER_LOGON
    $trig.UserId = $User
    $task.Principal.LogonType = 3             # TASK_LOGON_INTERACTIVE_TOKEN
    $registerLogonType = 3
}
$action = $task.Actions.Create(0)             # TASK_ACTION_EXEC
$action.Path = $Python
$action.Arguments = "-m atw --home `"$AtwHome`" service run"
$action.WorkingDirectory = $ProjectRoot

if ($Force) {
    try { $folder.DeleteTask($TaskName, 0) } catch { }
}
try {
    $folder.RegisterTaskDefinition($TaskName, $task, 6, $null, $null, $registerLogonType) | Out-Null
} catch {
    if ($TriggerType -eq "AtStartup") {
        throw "Registering an AtStartup/S4U task was denied ($($_.Exception.Message)). Run this script from an elevated PowerShell (or grant the 'Log on as a batch job' right). For a non-elevated functional check use -TriggerType AtLogOn, which is NOT equivalent to boot/no-login."
    }
    throw
}
Write-Host "registered task '$TaskName' (trigger=$TriggerType, user=$User, logonType=$registerLogonType)"

if (-not $NoStart) {
    if (Get-Process atw -ErrorAction SilentlyContinue) {
        Write-Warning "an 'atw' process is already running; starting the task may conflict with the single-instance lock"
    }
    $registered = $folder.GetTask($TaskName)
    $registered.Run($null) | Out-Null
    $deadline = (Get-Date).AddSeconds(30)
    $running = $false
    while ((Get-Date) -lt $deadline) {
        Start-Sleep -Milliseconds 500
        try {
            $status = (& $Python -m atw --home $AtwHome status --json 2>$null) | ConvertFrom-Json
            if ($status.service_running) { $running = $true; break }
        } catch { }
    }
    if (-not $running) {
        throw "task registered but ATW is not running within 30s; check Task Scheduler history and $(Join-Path $AtwHome 'logs\atw.log')"
    }
    Write-Host "ATW service is running (verified by atw status)."
}
Write-Host "Check: `"$Python`" -m atw --home `"$AtwHome`" doctor --json"
